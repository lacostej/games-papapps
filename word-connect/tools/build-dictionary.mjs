// Builds dictionaries/<code>/words.txt from a raw word list, then reports how many
// words each seed yields.  Usage: node tools/build-dictionary.mjs [code ...]
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { Language } from '../src/core/language.js';
import { Dictionary, parseWordList } from '../src/core/dictionary.js';
import { LANGUAGES } from '../src/data/languages.js';

const root = fileURLToPath(new URL('..', import.meta.url));
const sources = JSON.parse(readFileSync(`${root}/tools/dictionary-sources.json`, 'utf8'));
const codes = process.argv.slice(2).length ? process.argv.slice(2) : Object.keys(sources);
let failed = false;

for (const code of codes) {
  const config = sources[code];
  const definition = LANGUAGES.find((l) => l.code === code);
  if (!config || !definition) throw new Error(`No source or language definition for ${code}`);
  const language = new Language(definition);
  const sourcePath = config.source.startsWith('/') ? config.source : `${root}/${config.source}`;

  const words = new Set();
  for (const raw of parseWordList(readFileSync(sourcePath, 'utf8'))) {
    if (config.skipCapitalized && /^\p{Lu}/u.test(raw)) continue;
    const word = language.normalize(raw);
    if (!language.isPlayable(word)) continue;
    const length = language.tiles(word).length;
    if (length < language.minWordLength || length > language.maxTiles) continue;
    words.add(word);
    if (config.addSPlurals && length < language.maxTiles && !/[SXZ]$/.test(word)) {
      words.add(`${word}S`);
    }
  }

  const sorted = [...words].sort();
  const header = `# Generated by tools/build-dictionary.mjs from ${config.source}. Do not edit.\n`;
  writeFileSync(`${root}/dictionaries/${code}/words.txt`, header + sorted.join('\n') + '\n');

  const dictionary = new Dictionary(language, sorted);
  const seeds = parseWordList(readFileSync(`${root}/dictionaries/${code}/seeds.txt`, 'utf8'));
  console.log(`${code}: ${sorted.length} words`);
  for (const raw of seeds) {
    const seed = language.normalize(raw);
    if (!dictionary.has(seed)) {
      console.error(`  seed ${seed} is not in the dictionary`);
      failed = true;
      continue;
    }
    const count = dictionary.wordsFrom(language.tiles(seed)).length;
    console.log(`  ${seed.padEnd(8)} ${count}`);
  }
}

if (failed) process.exit(1);
